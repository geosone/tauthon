[CmdletBinding()]
param(
    [string]$PackageDirectory = (Join-Path $PSScriptRoot '../../tauthon-packages'),
    [string]$RelayRepository = (Join-Path $PSScriptRoot '../../mysticd-installer-work')
)
$ErrorActionPreference = 'Stop'
if (-not $IsLinux) { throw 'This test currently requires a Linux Docker host.' }
$PackageDirectory = (Resolve-Path $PackageDirectory).Path
$RelayRepository = (Resolve-Path $RelayRepository).Path
if (-not (Get-ChildItem -LiteralPath $PackageDirectory -Filter '*.deb')) { throw 'No Debian packages found.' }
$repository = Split-Path $PSScriptRoot -Parent
& docker build -f (Join-Path $PSScriptRoot 'trixie-test.Dockerfile') -t tauthon-test:trixie $PSScriptRoot
if ($LASTEXITCODE -ne 0) { throw 'Cannot build package acceptance image.' }
$lab = Join-Path ([IO.Path]::GetTempPath()) ('tauthon-mrc-' + [guid]::NewGuid().ToString('N'))
& (Join-Path $RelayRepository 'tools/Stage-MrcCompatibilityLab.ps1') -Bundled -OutputDirectory $lab
$test = @'
#!/bin/sh
# Runs inside the disposable build container, never on the production BBS.
set -eu
before=$(sha256sum /usr/bin/python3)
dpkg -i /packages/*.deb
/usr/bin/tauthon2.8 /source/debian/tests/runtime.py
/usr/bin/tauthon2.8 /source/debian/tests/layout.py
/usr/bin/python2 -c 'import sys; assert sys.version_info[:2] == (2, 8)'
/usr/bin/python2.7 -c 'import sys; assert sys.version_info[:2] == (2, 8)'
cat > /tmp/embed.c <<'C'
#include <Python.h>
int main(void) {
    Py_Initialize();
    int result = PyRun_SimpleString("import sys; assert sys.version_info[:2] == (2, 8)");
    Py_Finalize();
    return result != 0;
}
C
# Probe the old Debian addon path with a module rebuilt for Tauthon.
mkdir -p /usr/lib/python2.7/dist-packages
printf '%s\n' 'value = 42' > /usr/lib/python2.7/dist-packages/legacy_layout_probe.py
/usr/bin/python2.7 -c 'import legacy_layout_probe; assert legacy_layout_probe.value == 42'
cat > /tmp/legacy_native.c <<'C'
#include <Python.h>
static PyMethodDef methods[] = {{NULL, NULL, 0, NULL}};
PyMODINIT_FUNC initlegacy_native(void) { Py_InitModule("legacy_native", methods); }
C
triplet=$(/usr/bin/tauthon2.8 -c 'import sys; print(sys._multiarch)')
cc -fPIC -shared $(tauthon2.8-config --cflags) /tmp/legacy_native.c -o "/usr/lib/python2.7/dist-packages/legacy_native.$triplet.so" $(tauthon2.8-config --ldflags)
/usr/bin/python2.7 -c 'import legacy_native; assert "dist-packages" in legacy_native.__file__'
# Flags are generated by our installed development package.
cc $(tauthon2.8-config --cflags) /tmp/embed.c -o /tmp/embed $(tauthon2.8-config --ldflags)
/tmp/embed
python3 /relay/tests/test_python_multiplexer.py /lab --python /usr/bin/tauthon2.8
# Ensure all three Python-2 source files at least compile under Tauthon.
/usr/bin/tauthon2.8 -c 'import py_compile; [py_compile.compile("/lab/" + n, doraise=True) for n in ["mrc_server.py", "mrc_client.py", "mrc_compat.py"]]'
packages=$(for archive in /packages/*.deb; do dpkg-deb -f "$archive" Package; done)
dpkg --purge $packages
[ ! -e /usr/bin/python2 ]
[ ! -e /usr/bin/python2.7 ]
[ "$before" = "$(sha256sum /usr/bin/python3)" ]
printf '%s\n' 'PASS package installation/removal, optional aliases, native embedding and MRC multiplexer'

'@
try {
    & docker run --rm --network=none --mount "type=bind,src=$PackageDirectory,dst=/packages,readonly" --mount "type=bind,src=$repository,dst=/source,readonly" --mount "type=bind,src=$RelayRepository,dst=/relay,readonly" --mount "type=bind,src=$lab,dst=/lab" tauthon-test:trixie sh -ec $test
    if ($LASTEXITCODE -ne 0) { throw "Container acceptance failed with exit code $LASTEXITCODE" }
}
finally {
    if (Test-Path (Join-Path $lab '.mrc-compat-lab')) { Remove-Item -LiteralPath $lab -Recurse -Force }
}
